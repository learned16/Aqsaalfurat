def _write_json(path, data, created):
    if not os.path.exists(path):
        with open(path, 'w', encoding='utf-8') as fh:
            json.dump(data, fh, ensure_ascii=False, indent=2)
        created.append(os.path.basename(path))


def job_template(path):
    from openpyxl import Workbook
    from openpyxl.styles import Font, PatternFill, Alignment
    from factory import JOB_KEYS, ITEM_HEAD
    wb = Workbook()
    ws = wb.active
    ws.title = 'البيانات'
    ws.sheet_view.rightToLeft = True
    ws.append(['الحقل', 'القيمة', 'شرح'])
    for ar, _, hint in JOB_KEYS:
        ws.append([ar, '', hint])
    ws['B2'] = 'أقصى الفرات'
    for c in ws[1]:
        c.font = Font(bold=True)
        c.fill = PatternFill('solid', fgColor='D9E2F3')
    ws.column_dimensions['A'].width = 22
    ws.column_dimensions['B'].width = 45
    ws.column_dimensions['C'].width = 70
    for row in ws.iter_rows(min_row=2):
        row[0].font = Font(bold=True)
        row[2].font = Font(color='808080', size=9)
        row[1].alignment = Alignment(wrap_text=True)
    it = wb.create_sheet('المواد')
    it.sheet_view.rightToLeft = True
    it.append(ITEM_HEAD)
    for c in it[1]:
        c.font = Font(bold=True)
        c.fill = PatternFill('solid', fgColor='D9E2F3')
    it.column_dimensions['A'].width = 50
    for col in 'BCDE':
        it.column_dimensions[col].width = 16
    wb.save(path)


def docs_sheet(path):
    from openpyxl import Workbook
    from openpyxl.styles import Font
    wb = Workbook()
    ws = wb.active
    ws.title = 'المستمسكات'
    ws.sheet_view.rightToLeft = True
    for r in DOCS:
        ws.append(r)
    for c in ws[1]:
        c.font = Font(bold=True)
    ws.column_dimensions['B'].width = 40
    ws.column_dimensions['C'].width = 50
    ws.column_dimensions['D'].width = 16
    ws.column_dimensions['E'].width = 40
    wb.save(path)


def create(root):
    created = []
    os.makedirs(os.path.join(root, 'الجهات'), exist_ok=True)
    for sub in ('طلبات', os.path.join('طلبات', 'تم'), os.path.join('طلبات', 'فشل'), 'المستمسكات'):
        os.makedirs(os.path.join(root, sub), exist_ok=True)
    _write_json(os.path.join(root, 'الإعدادات.json'), SETTINGS, created)
    _write_json(os.path.join(root, 'الشركات.json'), COMPANIES, created)
    _write_json(os.path.join(root, 'الجهات', 'كهرباء الوسط.json'), ELECTRICITY, created)
    _write_json(os.path.join(root, 'الجهات', 'عام.json'), GENERAL, created)
    p = os.path.join(root, 'طلب مناقصة.xlsx')
    if not os.path.exists(p):
        job_template(p)
        created.append('طلب مناقصة.xlsx')
    p = os.path.join(root, 'مستمسكات.xlsx')
    if not os.path.exists(p):
        docs_sheet(p)
        created.append('مستمسكات.xlsx')
    p = os.path.join(root, 'اقرأني.txt')
    if not os.path.exists(p):
        with open(p, 'w', encoding='utf-8-sig') as fh:
            fh.write(README)
        created.append('اقرأني.txt')
    return created
